"""Converts a folder of v1 airport configs to v2 and writes the generated test cases.

Usage: python3 -m vsid_v2 <v1 dir> <v2 dir> --cases <cases dir> --report <report.md> [--results <file>]

--results: output of configcases_test on the written files, added to the report.
"""

import argparse
import json
import os
import re
import sys

from .cases import generate
from .convert import convert
from .v1model import load_v1

ACCEPTED = os.path.join(os.path.dirname(__file__), "accepted_differences.json")
RESULT_LINE = re.compile(r"^(\w+) cases=(\d+) ok=(\d+) accepted=(\d+) failed=(\d+)$")


def _write_json(path, value):
	with open(path, "w", encoding="utf-8") as f:
		json.dump(value, f, indent="\t", ensure_ascii=False)
		f.write("\n")


def _write_cases(path, cases):
	"""{icao: [case, ...]} with one compact case per line."""
	with open(path, "w", encoding="utf-8") as f:
		f.write("{\n")
		for n, (icao, items) in enumerate(cases.items()):
			f.write(f"{json.dumps(icao)}: [\n")
			f.write(",\n".join(json.dumps(c, ensure_ascii=False, separators=(",", ":")) for c in items))
			f.write("\n]" + (",\n" if n + 1 < len(cases) else "\n"))
		f.write("}\n")


def _read_results(path):
	"""{icao: (cases, ok, accepted, failed)} and {icao: [(count, reason)]} from configcases_test output."""
	totals, reasons = {}, {}
	icao = None
	with open(path, encoding="utf-8") as f:
		for line in f:
			m = RESULT_LINE.match(line.strip())
			if m:
				icao = m.group(1)
				totals[icao] = tuple(int(m.group(i)) for i in range(2, 6))
				continue
			m = re.match(r"^\s+accepted (\d+): (.*)$", line.rstrip("\n"))
			if m and icao:
				reasons.setdefault(icao, []).append((int(m.group(1)), m.group(2)))
	return totals, reasons


def report_markdown(rows, notes, accepted, results):
	lines = ["# vSID config v2 conversion report", "",
		"Generated by `python3 -m vsid_v2` (vSID repository, `tools/`). Each v1 airport file is rewritten in the v2 "
		"format (same file name). The v2 choice is checked against a reference model of the v1 choice on generated "
		"cases (`tests/configcases_test.cpp`); the differences accepted on purpose are listed in "
		"`tools/vsid_v2/accepted_differences.json`.", ""]

	nav = [(icao, rule) for icao, rules in accepted.items() if not icao.startswith("_")
		for rule in rules if rule["reason"].startswith("nav decision")]
	if nav:
		lines += ["## Differences to settle with the nav", "",
			"The v2 config gives another SID than v1 on these cases. Each one comes from a v1 config anomaly or from "
			"variants of equal `prio` that v1 separates by reading order only. Fixing the v1 config, or keeping the "
			"v2 behaviour, is up to the nav.", ""]
		for icao, rule in nav:
			where = ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in rule["match"].items())
			count = ""
			for n, reason in results[1].get(icao, []):
				if reason == rule["reason"]:
					count = f" ({n} cases)"
			lines.append(f"- **{icao}** {rule['reason'][len('nav decision: '):]}{count}  \n  cases: `{where}`")
		lines.append("")

	general = [rule for rule in accepted.get("*", [])]
	if general:
		lines += ["## Differences accepted on every airport", ""]
		for rule in general:
			lines.append(f"- {rule['reason']}")
		lines.append("- EQUIP: when no SID is found, v2 flags EQUIP if an entry was dropped only for its equipment "
			"(spec §4.3); v1 flagged it from the last variant read. Cases differing only by this flag are accepted.")
		lines.append("")

	totals = results[0]
	lines += ["## Airports", ""]
	header = "| Airport | v1 variants | v2 entries | cases |"
	sep = "|---|---|---|---|"
	if totals:
		header += " ok | accepted | failed |"
		sep += "---|---|---|"
	lines += [header, sep]
	for icao, variants, entries, cases in rows:
		row = f"| {icao} | {variants} | {entries} | {cases} |"
		if totals:
			t = totals.get(icao)
			row += f" {t[1]} | {t[2]} | {t[3]} |" if t else " - | - | - |"
		lines.append(row)
	lines.append("")

	lines += ["## Conversion notes", ""]
	for icao, airport_notes in notes:
		if not airport_notes:
			continue
		lines.append(f"### {icao}")
		lines.append("")
		for n in airport_notes:
			lines.append(f"- {n[len(icao) + 2:] if n.startswith(icao + ': ') else n}")
		lines.append("")
	return "\n".join(lines)


def main(argv=None):
	parser = argparse.ArgumentParser(prog="vsid_v2", description="Convert vSID v1 airport configs to v2.")
	parser.add_argument("src")
	parser.add_argument("dst")
	parser.add_argument("--cases", required=True)
	parser.add_argument("--report", required=True)
	parser.add_argument("--results")
	args = parser.parse_args(argv)

	os.makedirs(args.dst, exist_ok=True)
	os.makedirs(args.cases, exist_ok=True)
	with open(ACCEPTED, encoding="utf-8") as f:
		accepted = json.load(f)
	results = _read_results(args.results) if args.results else ({}, {})

	rows, notes = [], []
	for name in sorted(os.listdir(args.src)):
		if not name.endswith(".json"):
			continue
		with open(os.path.join(args.src, name), encoding="utf-8") as f:
			data = json.load(f)
		out, cases = {}, {}
		for icao, airport in data.items():
			ap = load_v1(icao, airport)
			out[icao], report = convert(ap)
			cases[icao] = generate(ap, out[icao])
			entries = sum(len(b["entries"] if isinstance(b, dict) else b) for b in out[icao]["procedures"].values())
			rows.append((icao, len(ap.variants), entries, len(cases[icao])))
			notes.append((icao, report[1:]))
		_write_json(os.path.join(args.dst, name), out)
		_write_cases(os.path.join(args.cases, name[:-len(".json")] + ".cases.json"), cases)
		print(f"{name}: " + ", ".join(f"{icao} {len(c)} cases" for icao, c in cases.items()))

	with open(args.report, "w", encoding="utf-8") as f:
		f.write(report_markdown(rows, notes, accepted, results))
	return 0


if __name__ == "__main__":
	sys.exit(main())
