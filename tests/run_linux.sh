#!/usr/bin/env bash
# Builds and runs the pure (EuroScope-free) unit tests with g++.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p build-linux

run_test() {
	local name="$1"; shift
	g++ -std=c++20 -O1 -Wall -I. -o "build-linux/$name" "$@"
	echo "== $name"
	"./build-linux/$name"
}

run_test autoconfiguration_test tests/autoconfiguration_test.cpp autoconfiguration.cpp
run_test bridgeconfiguration_test tests/bridgeconfiguration_test.cpp autoconfiguration.cpp
run_test sidconfigv2_test tests/sidconfigv2_test.cpp sidconfigv2.cpp
run_test sidengine_test tests/sidengine_test.cpp sidengine.cpp sidconfigv2.cpp
run_test strategy_test tests/strategy_test.cpp strategy.cpp sidconfigv2.cpp

# v2 configs replayed against the v1 choice (cases generated by tools/vsid_v2)
g++ -std=c++20 -O2 -Wall -I. -o build-linux/configcases_test tests/configcases_test.cpp sidengine.cpp sidconfigv2.cpp
for airport in lfpg lfpo lfpn lfbo; do
	echo "== configcases_test $airport"
	./build-linux/configcases_test "tests/data/$airport.v2.json" "tests/data/$airport.cases.json" tools/vsid_v2/accepted_differences.json
done
